/* Sampling Sphere · satellite eye: how each instrument looks at the Earth.
   Types: whisk (a mirror sweeps a line across the swath), step (a sounder clicks across in discrete spots), push (a pushbroom line,
   always on), frame (a camera taking frames), conical (a spot riding an arc ahead or behind), sar (radar strips to one or both sides),
   alt (altimeter spot straight down), lidar (laser beams), ro (GNSS radio occultation at the horizon), geo (a geostationary imager
   rastering its disk), pair (two satellites ranging to each other), ring (tasked or unknown: only where it is, not when it looks).
   Units: km and seconds. src 'OSCAR' = numbers read from WMO OSCAR/Space (2026-10-29); 'approx' = typical published values. */
